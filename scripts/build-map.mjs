// Converts the openpolis regions GeoJSON into simplified SVG paths (src/data/mapPaths.js).
import { readFileSync, writeFileSync } from 'node:fs'

const geo = JSON.parse(readFileSync(new URL('./limits_IT_regions.geojson', import.meta.url), 'utf8'))

const NAMES = {
  "Valle d'Aosta/Vallée d'Aoste": "Valle d'Aosta",
  'Trentino-Alto Adige/Südtirol': 'Trentino-Alto Adige',
}
const SCALE = 100 // px per degree of latitude
const LAT0 = 42
const TOLERANCE = 0.006 // degrees, Douglas-Peucker

const kx = Math.cos((LAT0 * Math.PI) / 180)
const [minLon, minLat, maxLon, maxLat] = geo.bbox
const project = ([lon, lat]) => [(lon - minLon) * kx * SCALE, (maxLat - lat) * SCALE]

function simplify(pts, tol) {
  if (pts.length < 3) return pts
  const keep = new Uint8Array(pts.length)
  keep[0] = keep[pts.length - 1] = 1
  const stack = [[0, pts.length - 1]]
  while (stack.length) {
    const [a, b] = stack.pop()
    let max = 0, idx = -1
    const [ax, ay] = pts[a], [bx, by] = pts[b]
    const dx = bx - ax, dy = by - ay, len = Math.hypot(dx, dy) || 1e-12
    for (let i = a + 1; i < b; i++) {
      const d = Math.abs(dy * pts[i][0] - dx * pts[i][1] + bx * ay - by * ax) / len
      if (d > max) { max = d; idx = i }
    }
    if (max > tol) { keep[idx] = 1; stack.push([a, idx], [idx, b]) }
  }
  return pts.filter((_, i) => keep[i])
}

const ringPath = (ring) => {
  // a closed ring has identical endpoints, so simplify each half separately
  const mid = Math.floor(ring.length / 2)
  const pts = [...simplify(ring.slice(0, mid + 1), TOLERANCE).slice(0, -1), ...simplify(ring.slice(mid), TOLERANCE)]
  if (pts.length < 4) return ''
  const p = pts.map(project)
  return 'M' + p.map(([x, y]) => `${x.toFixed(1)} ${y.toFixed(1)}`).join('L') + 'Z'
}

const regions = geo.features.map((f) => {
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates
  const d = polys.map((rings) => rings.map(ringPath).join('')).join('')
  const name = NAMES[f.properties.reg_name] ?? f.properties.reg_name
  return { id: f.properties.reg_istat_code, name, d }
})

const width = Math.ceil((maxLon - minLon) * kx * SCALE)
const height = Math.ceil((maxLat - minLat) * SCALE)
const out = `// Generated by scripts/build-map.mjs — do not edit.
export const MAP_VIEWBOX = '0 0 ${width} ${height}'
export const MAP_PATHS = ${JSON.stringify(regions, null, 2)}
`
writeFileSync(new URL('../src/data/mapPaths.js', import.meta.url), out)
console.log(`${regions.length} regions, ${(out.length / 1024).toFixed(0)} KB, viewBox ${width}x${height}`)
